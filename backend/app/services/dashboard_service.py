"""Builds the Command Center dashboard and the daily business brief.

All numbers here come directly from SQL queries against real records --
nothing is fabricated. Recommendations are generated by simple, explainable
rules (not free-form LLM text) so they can never claim something false;
each one states a reason you can verify against the underlying data.
"""
from datetime import datetime, timedelta, timezone

from sqlalchemy.orm import Session

from app.models.audit import AuditLog
from app.models.crm import Lead
from app.models.finance import Invoice, Quotation
from app.models.tasks import FollowUp, Task


def _now():
    return datetime.now(timezone.utc)


def get_dashboard_data(db: Session, business) -> dict:
    now = _now()
    business_id = business.id

    overdue_tasks = (
        db.query(Task)
        .filter(
            Task.business_id == business_id,
            Task.status != "DONE",
            Task.due_date.isnot(None),
            Task.due_date < now,
        )
        .order_by(Task.due_date.asc())
        .all()
    )

    urgent_tasks = (
        db.query(Task)
        .filter(
            Task.business_id == business_id,
            Task.status != "DONE",
            Task.priority.in_(["HIGH", "URGENT"]),
        )
        .order_by(Task.due_date.asc().nullslast())
        .limit(10)
        .all()
    )

    week_ago = now - timedelta(days=7)
    new_leads = (
        db.query(Lead)
        .filter(Lead.business_id == business_id, Lead.created_at >= week_ago)
        .order_by(Lead.created_at.desc())
        .all()
    )

    overdue_follow_ups = (
        db.query(FollowUp)
        .filter(
            FollowUp.business_id == business_id,
            FollowUp.status == "PENDING",
            FollowUp.due_at < now,
        )
        .order_by(FollowUp.due_at.asc())
        .all()
    )

    stale_threshold = now - timedelta(days=business.stale_lead_days_threshold)
    stale_leads = (
        db.query(Lead)
        .filter(
            Lead.business_id == business_id,
            Lead.status.notin_(["WON", "LOST"]),
        )
        .filter(
            (Lead.last_activity_at.is_(None) & (Lead.created_at < stale_threshold))
            | (Lead.last_activity_at < stale_threshold)
        )
        .all()
    )

    quotations_awaiting_approval = (
        db.query(Quotation)
        .filter(Quotation.business_id == business_id, Quotation.status == "PENDING_APPROVAL")
        .all()
    )

    overdue_invoices = (
        db.query(Invoice)
        .filter(
            Invoice.business_id == business_id,
            Invoice.status.in_(["ISSUED", "PARTIALLY_PAID"]),
            Invoice.due_date.isnot(None),
            Invoice.due_date < now,
        )
        .all()
    )

    recent_activity = (
        db.query(AuditLog)
        .filter(AuditLog.business_id == business_id)
        .order_by(AuditLog.created_at.desc())
        .limit(15)
        .all()
    )

    recommendations = []
    if overdue_follow_ups:
        recommendations.append(
            {
                "text": f"{len(overdue_follow_ups)} follow-up(s) are overdue.",
                "reason": "No action recorded past their due date.",
                "priority": "HIGH",
                "link": "/tasks",
            }
        )
    if stale_leads:
        recommendations.append(
            {
                "text": f"{len(stale_leads)} lead(s) have had no activity in "
                f"{business.stale_lead_days_threshold}+ days.",
                "reason": "Configured stale-lead threshold exceeded.",
                "priority": "MEDIUM",
                "link": "/leads",
            }
        )
    if quotations_awaiting_approval:
        recommendations.append(
            {
                "text": f"{len(quotations_awaiting_approval)} quotation(s) are waiting for your approval.",
                "reason": "Status is PENDING_APPROVAL.",
                "priority": "HIGH",
                "link": "/quotes",
            }
        )
    if overdue_invoices:
        recommendations.append(
            {
                "text": f"{len(overdue_invoices)} invoice(s) are past their due date.",
                "reason": "Due date has passed and payment is incomplete.",
                "priority": "HIGH",
                "link": "/invoices",
            }
        )
    if overdue_tasks:
        recommendations.append(
            {
                "text": f"{len(overdue_tasks)} task(s) are overdue.",
                "reason": "Due date has passed and task is not done.",
                "priority": "MEDIUM",
                "link": "/tasks",
            }
        )

    def _task_dict(t: Task) -> dict:
        return {
            "id": t.id, "title": t.title, "priority": t.priority, "status": t.status,
            "due_date": t.due_date.isoformat() if t.due_date else None,
        }

    def _lead_dict(l: Lead) -> dict:
        return {
            "id": l.id, "title": l.title, "status": l.status, "value": l.value,
            "next_follow_up": l.next_follow_up.isoformat() if l.next_follow_up else None,
        }

    return {
        "urgent_tasks": [_task_dict(t) for t in urgent_tasks],
        "new_leads": [_lead_dict(l) for l in new_leads],
        "leads_needing_follow_up": [_lead_dict(l) for l in stale_leads],
        "quotations_awaiting_approval": [
            {"id": q.id, "number": q.number, "total": q.total, "status": q.status}
            for q in quotations_awaiting_approval
        ],
        "overdue_tasks": [_task_dict(t) for t in overdue_tasks],
        "invoice_alerts": [
            {"id": i.id, "number": i.number, "total": i.total, "due_date": i.due_date.isoformat() if i.due_date else None}
            for i in overdue_invoices
        ],
        "recent_activity": [
            {
                "id": a.id, "actor": a.actor, "action": a.action,
                "created_at": a.created_at.isoformat(), "success": a.success,
            }
            for a in recent_activity
        ],
        "recommendations": recommendations,
    }


def generate_daily_brief(db: Session, business) -> dict:
    data = get_dashboard_data(db, business)
    parts = []
    if data["overdue_tasks"]:
        parts.append(f"{len(data['overdue_tasks'])} task(s) overdue")
    if data["new_leads"]:
        parts.append(f"{len(data['new_leads'])} new lead(s) this week")
    if data["leads_needing_follow_up"]:
        parts.append(f"{len(data['leads_needing_follow_up'])} lead(s) going cold")
    if data["quotations_awaiting_approval"]:
        parts.append(f"{len(data['quotations_awaiting_approval'])} quotation(s) awaiting approval")
    if data["invoice_alerts"]:
        parts.append(f"{len(data['invoice_alerts'])} invoice(s) overdue")

    summary_text = (
        "Today: " + ", ".join(parts) + "."
        if parts
        else "No urgent items today. Everything on track."
    )

    return {
        "generated_at": _now().isoformat(),
        "urgent_tasks_count": len(data["urgent_tasks"]),
        "new_leads_count": len(data["new_leads"]),
        "overdue_follow_ups_count": len(data["leads_needing_follow_up"]),
        "pending_quotations_count": len(data["quotations_awaiting_approval"]),
        "important_invoices_count": len(data["invoice_alerts"]),
        "summary_text": summary_text,
        "recommendations": data["recommendations"],
    }
