// Generates supabase/migrations/*_seed.sql from src/content/catalog.json so the
// database seed and the website's offline fallback never drift apart.
// Usage: node scripts/generate-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const catalog = JSON.parse(readFileSync(join(root, "src/content/catalog.json"), "utf8"));

const lit = (v) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  return "'" + String(v).replaceAll("'", "''") + "'";
};
const json = (v) => lit(JSON.stringify(v)) + "::jsonb";

export function buildSeedSql(services) {
  const cols = [
    "slug", "category", "name", "tagline", "description", "price_min_cents", "price_max_cents",
    "price_notes", "billing_type", "purchase_mode", "deposit_percent", "deliverables", "exclusions",
    "revisions_included", "timeline_text", "is_featured", "sort_order",
  ];
  const rows = services.map((s) => {
    const vals = [
      lit(s.slug), lit(s.category), lit(s.name), lit(s.tagline), lit(s.description),
      lit(s.price_min_cents), lit(s.price_max_cents), lit(s.price_notes ?? null), lit(s.billing_type),
      lit(s.purchase_mode), lit(s.deposit_percent), json(s.deliverables), json(s.exclusions),
      lit(s.revisions_included), lit(s.timeline_text), lit(s.is_featured), lit(s.sort_order),
    ];
    return `  (${vals.join(", ")})`;
  });
  return [
    "-- GENERATED by scripts/generate-seed.mjs from src/content/catalog.json. Do not edit by hand.",
    "-- Seeds the default catalogue once. Existing rows (matched by slug) are left untouched so",
    "-- prices you edit in the admin dashboard are never overwritten.",
    "",
    "insert into public.business_settings (id) values (1) on conflict (id) do nothing;",
    "",
    `insert into public.services (${cols.join(", ")}) values`,
    rows.join(",\n"),
    "on conflict (slug) do nothing;",
    "",
  ].join("\n");
}

const out = join(root, "supabase/migrations/20261117000005_seed.sql");
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(out, buildSeedSql(catalog.services));
  console.log(`Wrote ${out} (${catalog.services.length} services)`);
}
